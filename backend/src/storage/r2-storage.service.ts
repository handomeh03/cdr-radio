import { createReadStream } from 'node:fs';
import { Injectable, OnModuleDestroy } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
  S3ServiceException,
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import type { EnvironmentVariables } from '../config/env.validation.js';

/** Raised for any storage failure; carries no credentials, URLs or paths. */
export class StorageError extends Error {
  constructor(
    readonly operation: 'upload' | 'delete' | 'head' | 'presign',
    readonly reason: string,
  ) {
    super(`Storage ${operation} failed (${reason})`);
    this.name = 'StorageError';
  }
}

export interface StoredObjectInfo {
  sizeBytes: number;
  contentType: string | undefined;
}

/** Keys are generated by the backend (e.g. tracks/{uuid}.mp3), never taken from user input. */
const SAFE_KEY = /^[a-z0-9-]+(\/[a-z0-9-]+)*\.[a-z0-9]+$/;

/**
 * Private Cloudflare R2 bucket via the S3 API. One client for the whole app.
 * Objects are never public: access is only via these server-side calls or short-lived presigned GETs.
 */
@Injectable()
export class R2StorageService implements OnModuleDestroy {
  private readonly client: S3Client;
  private readonly bucket: string;
  private readonly presignTtlSeconds: number;

  constructor(config: ConfigService<EnvironmentVariables, true>) {
    this.bucket = config.get('R2_BUCKET_NAME', { infer: true });
    this.presignTtlSeconds = config.get('R2_PRESIGN_TTL_SECONDS', {
      infer: true,
    });
    this.client = new S3Client({
      region: 'auto',
      endpoint: config.get('R2_ENDPOINT', { infer: true }),
      credentials: {
        accessKeyId: config.get('R2_ACCESS_KEY_ID', { infer: true }),
        secretAccessKey: config.get('R2_SECRET_ACCESS_KEY', { infer: true }),
      },
      // R2 does not need the SDK's default extra checksums; only send them when an operation requires it.
      requestChecksumCalculation: 'WHEN_REQUIRED',
      responseChecksumValidation: 'WHEN_REQUIRED',
      maxAttempts: 3,
    });
  }

  onModuleDestroy(): void {
    this.client.destroy();
  }

  /** Uploads a local file. No ACL is set: objects inherit the bucket's private access. */
  async uploadFile(
    key: string,
    filePath: string,
    contentType: string,
    sizeBytes: number,
  ): Promise<void> {
    assertSafeKey(key, 'upload');
    await this.run('upload', () =>
      this.client.send(
        new PutObjectCommand({
          Bucket: this.bucket,
          Key: key,
          Body: createReadStream(filePath),
          ContentLength: sizeBytes,
          ContentType: contentType,
        }),
      ),
    );
  }

  /** Idempotent: deleting a missing object succeeds. */
  async deleteObject(key: string): Promise<void> {
    assertSafeKey(key, 'delete');
    await this.run('delete', () =>
      this.client.send(
        new DeleteObjectCommand({ Bucket: this.bucket, Key: key }),
      ),
    );
  }

  /** Object metadata, or null when it does not exist. */
  async headObject(key: string): Promise<StoredObjectInfo | null> {
    assertSafeKey(key, 'head');
    try {
      const head = await this.client.send(
        new HeadObjectCommand({ Bucket: this.bucket, Key: key }),
      );
      return {
        sizeBytes: head.ContentLength ?? 0,
        contentType: head.ContentType,
      };
    } catch (error) {
      if (
        error instanceof S3ServiceException &&
        error.$metadata.httpStatusCode === 404
      ) {
        return null;
      }
      throw toStorageError('head', error);
    }
  }

  /** Time-limited GET URL for server-side consumers (e.g. the playout engine). Never make it permanent. */
  async getPresignedGetUrl(
    key: string,
    ttlSeconds: number = this.presignTtlSeconds,
  ): Promise<{ url: string; expiresAt: Date }> {
    assertSafeKey(key, 'presign');
    const expiresIn = Math.min(ttlSeconds, this.presignTtlSeconds);
    const url = await this.run('presign', () =>
      getSignedUrl(
        this.client,
        new GetObjectCommand({ Bucket: this.bucket, Key: key }),
        {
          expiresIn,
        },
      ),
    );
    return { url, expiresAt: new Date(Date.now() + expiresIn * 1000) };
  }

  private async run<T>(
    operation: StorageError['operation'],
    fn: () => Promise<T>,
  ): Promise<T> {
    try {
      return await fn();
    } catch (error) {
      throw toStorageError(operation, error);
    }
  }
}

function assertSafeKey(
  key: string,
  operation: StorageError['operation'],
): void {
  if (!SAFE_KEY.test(key))
    throw new StorageError(operation, 'invalid object key');
}

function toStorageError(
  operation: StorageError['operation'],
  error: unknown,
): StorageError {
  if (error instanceof StorageError) return error;
  if (error instanceof S3ServiceException) {
    return new StorageError(
      operation,
      `${error.name}, HTTP ${error.$metadata.httpStatusCode ?? 'n/a'}`,
    );
  }
  return new StorageError(
    operation,
    error instanceof Error ? error.name : 'unknown error',
  );
}
